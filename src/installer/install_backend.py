#!/usr/bin/env python3
"""
GeminiOS 1.0 Disk Installation Backend (`install_backend.py`)
Runs as root (via pkexec from gemini_installer.py or standalone CLI) to install
GeminiOS from the Live SquashFS onto a target block device (UEFI or BIOS).
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

TARGET = Path("/mnt/geminios-target")


def run(cmd, check=True, env=None):
    print(f"[installer] $ {' '.join(str(c) for c in cmd)}", flush=True)
    return subprocess.run(cmd, check=check, env=env)


def progress(pct: int, msg: str):
    print(f"PROGRESS:{pct}:{msg}", flush=True)


def partition_path(disk: str, part_num: int) -> str:
    if any(disk.endswith(d) for d in "0123456789"):
        return f"{disk}p{part_num}"
    return f"{disk}{part_num}"


def get_uuid(dev: str) -> str:
    proc = subprocess.run(["blkid", "-s", "UUID", "-o", "value", dev], capture_output=True, text=True)
    return proc.stdout.strip()


def detect_uefi() -> bool:
    return Path("/sys/firmware/efi").exists()


def partition_and_format(disk: str, fs: str, uefi: bool):
    progress(10, f"Partitioning {disk} ({'UEFI/GPT' if uefi else 'BIOS/GPT'})...")
    run(["wipefs", "-af", disk], check=False)
    run(["parted", "-s", disk, "mklabel", "gpt"])

    if uefi:
        run(["parted", "-s", disk, "mkpart", "ESP", "fat32", "1MiB", "513MiB"])
        run(["parted", "-s", disk, "set", "1", "esp", "on"])
        run(["parted", "-s", disk, "mkpart", "GeminiRoot", fs, "513MiB", "100%"])
    else:
        run(["parted", "-s", disk, "mkpart", "BIOSBOOT", "1MiB", "3MiB"])
        run(["parted", "-s", disk, "set", "1", "bios_grub", "on"])
        run(["parted", "-s", disk, "mkpart", "GeminiRoot", fs, "3MiB", "100%"])

    run(["partprobe", disk], check=False)
    run(["udevadm", "settle"], check=False)

    p1 = partition_path(disk, 1)
    p2 = partition_path(disk, 2)

    progress(18, f"Formatting partitions ({fs})...")
    if uefi:
        run(["mkfs.fat", "-F32", "-n", "GEMINIEFI", p1])

    if fs == "btrfs":
        run(["mkfs.btrfs", "-f", "-L", "GeminiOS", p2])
    else:
        run(["mkfs.ext4", "-F", "-L", "GeminiOS", p2])

    return p1, p2


def mount_target(p1: str, p2: str, uefi: bool):
    TARGET.mkdir(parents=True, exist_ok=True)
    run(["mount", p2, str(TARGET)])
    if uefi:
        (TARGET / "boot/efi").mkdir(parents=True, exist_ok=True)
        run(["mount", p1, str(TARGET / "boot/efi")])


def copy_rootfs():
    progress(30, "Extracting GeminiOS system image to disk (this may take 1-3 minutes)...")
    sfs_file = Path("/run/geminios/medium/live/filesystem.squashfs")
    sfs_mount = Path("/run/geminios/sfs")

    if sfs_file.exists() and shutil.which("unsquashfs"):
        run(["unsquashfs", "-f", "-d", str(TARGET), str(sfs_file)])
    elif sfs_mount.exists() and shutil.which("rsync"):
        run(["rsync", "-aAXH", "--info=progress2", f"{sfs_mount}/", f"{TARGET}/"])
    else:
        run([
            "rsync", "-aAXH",
            "--exclude=/dev/*", "--exclude=/proc/*", "--exclude=/sys/*",
            "--exclude=/tmp/*", "--exclude=/run/*", "--exclude=/mnt/*",
            "--exclude=/media/*", "--exclude=/lost+found",
            "/", f"{TARGET}/",
        ])

    for d in ("dev", "proc", "sys", "run", "tmp"):
        (TARGET / d).mkdir(parents=True, exist_ok=True)


def write_fstab(p1: str, p2: str, fs: str, uefi: bool, swap_gb: int):
    progress(62, "Generating /etc/fstab and swap...")
    lines = ["# /etc/fstab: generated by GeminiOS Installer"]
    root_uuid = get_uuid(p2)
    root_opts = "defaults,noatime" if fs == "ext4" else "defaults,noatime,compress=zstd"
    lines.append(f"UUID={root_uuid}  /  {fs}  {root_opts}  0  1")

    if uefi:
        efi_uuid = get_uuid(p1)
        lines.append(f"UUID={efi_uuid}  /boot/efi  vfat  umask=0077  0  2")

    if swap_gb > 0:
        swapfile = TARGET / "swapfile"
        run(["fallocate", "-l", f"{swap_gb}G", str(swapfile)], check=False)
        if not swapfile.exists() or swapfile.stat().st_size == 0:
            run(["dd", "if=/dev/zero", f"of={swapfile}", "bs=1M", f"count={swap_gb * 1024}", "status=none"])
        os.chmod(swapfile, 0o600)
        run(["mkswap", str(swapfile)])
        lines.append("/swapfile  none  swap  defaults  0  0")

    (TARGET / "etc/fstab").write_text("\n".join(lines) + "\n", encoding="utf-8")


def configure_system(args, disk: str, uefi: bool):
    progress(72, "Configuring user account, locale, Gemini AI, and bootloader...")

    (TARGET / "etc/hostname").write_text(f"{args.hostname}\n", encoding="utf-8")
    (TARGET / "etc/hosts").write_text(
        f"127.0.0.1 localhost\n::1 localhost\n127.0.1.1 {args.hostname}.localdomain {args.hostname}\n",
        encoding="utf-8",
    )
    (TARGET / "etc/vconsole.conf").write_text(f"KEYMAP={args.keymap}\n", encoding="utf-8")

    # Apply Gemini API key if provided
    if args.api_key:
        gconf = TARGET / "etc/geminid/geminid.conf"
        if gconf.exists():
            text = gconf.read_text(encoding="utf-8")
            text = text.replace('api_key = ""', f'api_key = "{args.api_key}"', 1)
            gconf.write_text(text, encoding="utf-8")

    # Remove live installer desktop icon from installed system
    for icon in [
        TARGET / "home/gemini/Desktop/geminios-installer.desktop",
        TARGET / "etc/skel/Desktop/geminios-installer.desktop",
    ]:
        if icon.exists():
            icon.unlink()

    # Bind pseudo-filesystems for chroot
    for mp in ("dev", "dev/pts", "proc", "sys", "run"):
        (TARGET / mp).mkdir(parents=True, exist_ok=True)
        run(["mount", "--bind", f"/{mp}", str(TARGET / mp)], check=False)

    grub_modules = "part_gpt part_msdos all_video png gfxterm video_fb"
    grub_install_cmd = (
        f"grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=GeminiOS --modules='{grub_modules}' --recheck"
        if uefi
        else f"grub-install --target=i386-pc --modules='{grub_modules}' --recheck {disk}"
    )

    arch_cmd = "gem repo enable arch || true" if args.enable_arch else "true"
    aur_cmd = "gem repo enable aur || true" if args.enable_aur else "true"

    # User account configuration
    if args.username != "gemini":
        run(["chroot", str(TARGET), "userdel", "-f", "-r", "gemini"], check=False)
        for p_file in [TARGET / "etc/passwd", TARGET / "etc/shadow", TARGET / "etc/group", TARGET / "etc/gshadow"]:
            if p_file.exists():
                lines = [l for l in p_file.read_text(encoding="utf-8").splitlines() if not l.startswith("gemini:")]
                p_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
        shutil.rmtree(TARGET / "home/gemini", ignore_errors=True)

    check_u = subprocess.run(["chroot", str(TARGET), "id", args.username], capture_output=True)
    if check_u.returncode != 0:
        run(["chroot", str(TARGET), "useradd", "-m", "-G", "wheel,audio,video,storage", "-s", "/bin/zsh", args.username])

    home_dir = TARGET / f"home/{args.username}"
    skel_dir = TARGET / "etc/skel"
    if skel_dir.exists() and home_dir.exists():
        run(["rsync", "-a", f"{skel_dir}/", f"{home_dir}/"], check=False)
        run(["chroot", str(TARGET), "chown", "-R", f"{args.username}:{args.username}", f"/home/{args.username}"], check=False)

    pass_data = f"{args.username}:{args.password}\nroot:{args.password}\n"
    subprocess.run(["chroot", str(TARGET), "chpasswd"], input=pass_data, text=True, check=True)

    sudoers_drop = TARGET / "etc/sudoers.d/10-wheel"
    sudoers_drop.write_text("%wheel ALL=(ALL:ALL) ALL\n", encoding="utf-8")
    os.chmod(sudoers_drop, 0o440)

    sddm_state_dir = TARGET / "var/lib/sddm"
    sddm_state_dir.mkdir(parents=True, exist_ok=True)
    (sddm_state_dir / "state.conf").write_text(f"[Users]\nLastUser={args.username}\n", encoding="utf-8")

    chroot_script = f"""set -euo pipefail
ln -sf /usr/share/zoneinfo/{args.timezone} /etc/localtime
hwclock --systohc || true
sed -i 's/^#en_US.UTF-8/en_US.UTF-8/' /etc/locale.gen
sed -i 's/^#ru_RU.UTF-8/ru_RU.UTF-8/' /etc/locale.gen
locale-gen || true
echo "LANG=en_US.UTF-8" > /etc/locale.conf

# Ensure system is strictly identified as GeminiOS (clean Arch release files)
rm -f /etc/arch-release /etc/arch-release.pacnew
ln -sf /etc/os-release /usr/lib/os-release
echo "GeminiOS 1.0.1 (Spark) \\r (\\l)" > /etc/issue
echo "GeminiOS 1.0.1 (Spark)" > /etc/issue.net
echo "GeminiOS 1.0.1 (Spark)" > /etc/motd
echo "GeminiOS 1.0.1 (Spark)" > /etc/geminios-release
cat > /etc/lsb-release <<'LSBEOF'
DISTRIB_ID=GeminiOS
DISTRIB_RELEASE=1.0.1
DISTRIB_CODENAME=spark
DISTRIB_DESCRIPTION="GeminiOS 1.0.1 (Spark)"
LSBEOF

# Remove Live ISO autologin so installed system prompts for user password
rm -f /etc/sddm.conf.d/20-autologin.conf

# Pin Linux kernel 7.3.5 in pacman configuration
if [ -f /etc/pacman.conf ]; then
    sed -i 's/^#IgnorePkg =.*/IgnorePkg = linux linux-headers/' /etc/pacman.conf
    if ! grep -q "^IgnorePkg = linux linux-headers" /etc/pacman.conf; then
        sed -i '/\\[options\\]/a IgnorePkg = linux linux-headers' /etc/pacman.conf
    fi
fi

# Standard disk initramfs with Plymouth OLED boot splash (removes geminios-live hook)
cat > /etc/mkinitcpio.conf <<'MKCONF'
MODULES=()
BINARIES=()
FILES=()
HOOKS=(base udev plymouth autodetect modconf kms keyboard keymap consolefont block filesystems fsck)
MKCONF
mkinitcpio -P

# Configure GRUB2 with GeminiOS Dark theme + quiet splash and PNG module preloading
cat > /etc/default/grub <<'GRUBDEF'
GRUB_DEFAULT=0
GRUB_TIMEOUT=4
GRUB_DISTRIBUTOR="GeminiOS"
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash loglevel=3 rd.udev.log_priority=3 vt.global_cursor_default=0"
GRUB_CMDLINE_LINUX=""
GRUB_GFXMODE=auto
GRUB_THEME="/boot/grub/themes/geminios/theme.txt"
GRUB_PRELOAD_MODULES="part_gpt part_msdos all_video png gfxterm"
GRUBDEF

rm -f /etc/grub.d/01_geminios_header
cat > /etc/grub.d/00_0_geminios_preloads <<'GRUBHEADER'
#!/bin/sh
cat <<'EOF'
insmod part_gpt
insmod part_msdos
insmod all_video
insmod gfxterm
insmod png
insmod jpeg
EOF
GRUBHEADER
chmod +x /etc/grub.d/00_0_geminios_preloads

{grub_install_cmd}
grub-mkconfig -o /boot/grub/grub.cfg

{arch_cmd}
{aur_cmd}
"""
    progress(82, "Building disk initramfs & installing GRUB2 bootloader...")
    run(["chroot", str(TARGET), "/bin/bash", "-c", chroot_script])


def cleanup_mounts():
    progress(96, "Unmounting target filesystems...")
    for mp in ("run", "sys", "proc", "dev/pts", "dev", "boot/efi"):
        run(["umount", "-lf", str(TARGET / mp)], check=False)
    run(["umount", "-lf", str(TARGET)], check=False)


def main() -> int:
    parser = argparse.ArgumentParser(description="GeminiOS Disk Installation Backend")
    parser.add_argument("--disk", required=True, help="Target block device, e.g. /dev/vda or /dev/nvme0n1")
    parser.add_argument("--fs", choices=["ext4", "btrfs"], default="ext4")
    parser.add_argument("--swap-gb", type=int, default=4)
    parser.add_argument("--username", required=True)
    parser.add_argument("--password", required=True)
    parser.add_argument("--hostname", default="geminios")
    parser.add_argument("--timezone", default="Europe/Kyiv")
    parser.add_argument("--keymap", default="us")
    parser.add_argument("--api-key", default="")
    parser.add_argument("--enable-arch", action="store_true")
    parser.add_argument("--enable-aur", action="store_true")
    args = parser.parse_args()

    if os.geteuid() != 0:
        print("ERROR: install_backend.py must run as root.", file=sys.stderr)
        return 1

    uefi = detect_uefi()
    try:
        p1, p2 = partition_and_format(args.disk, args.fs, uefi)
        mount_target(p1, p2, uefi)
        copy_rootfs()
        write_fstab(p1, p2, args.fs, uefi, args.swap_gb)
        configure_system(args, args.disk, uefi)
    finally:
        cleanup_mounts()

    progress(98, "Присоединяйтесь к комьюнити: чат ОПГ «Радуга» (https://t.me/OPG_R4duga)...")
    progress(100, "GeminiOS 1.0.1 installation complete! Чат комьюнити ОПГ «Радуга»: https://t.me/OPG_R4duga")
    return 0


if __name__ == "__main__":
    sys.exit(main())
