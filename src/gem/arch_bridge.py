#!/usr/bin/env python3
"""
GeminiOS Arch Linux & AUR Bridge (`arch_bridge.py`)
Enables seamless installation of standard Arch Linux official repository packages
and AUR packages (via yay or native AUR RPC + makepkg) directly from `gem`.
"""

import json
import os
try:
    import pwd
except ImportError:
    pwd = None
import shutil
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional


ARCH_PACMAN_CONF_TEMPLATE = """# Auto-generated by GeminiOS `gem repo enable arch`
[options]
HoldPkg     = pacman glibc
IgnorePkg   = linux linux-headers
Architecture = x86_64
Color
CheckSpace
ParallelDownloads = 5
SigLevel    = DatabaseOptional
LocalFileSigLevel = Optional

[core]
Server = {mirror}

[extra]
Server = {mirror}

[multilib]
Server = {mirror}
"""


class ArchBridge:
    def __init__(self, config: Dict):
        self.cfg = config
        self.arch_cfg = config.get("bridge", {}).get("arch", {})
        self.aur_cfg = config.get("bridge", {}).get("aur", {})
        self.pacman_conf = Path(self.arch_cfg.get("pacman_conf", "/etc/gem/arch-pacman.conf"))
        self.mirror = self.arch_cfg.get("mirror", "https://geo.mirror.pkgbuild.com/$repo/os/$arch")
        self.rpc_url = self.aur_cfg.get("rpc_url", "https://aur.archlinux.org/rpc/v5")
        self.build_dir = Path(self.aur_cfg.get("build_dir", "/var/cache/gem/aur-build"))
        self.build_user = self.aur_cfg.get("build_user", "gembuilder")

    def is_arch_enabled(self) -> bool:
        return bool(self.arch_cfg.get("enabled", False))

    def is_aur_enabled(self) -> bool:
        return bool(self.aur_cfg.get("enabled", False))

    def _run(self, cmd: List[str], check: bool = True, user: Optional[str] = None) -> subprocess.CompletedProcess:
        if user and os.geteuid() == 0:
            cmd = ["sudo", "-u", user] + cmd
        return subprocess.run(cmd, check=check)

    def ensure_build_user(self) -> None:
        try:
            pwd.getpwnam(self.build_user)
        except KeyError:
            self._run(["useradd", "-m", "-s", "/bin/bash", "-G", "wheel", self.build_user], check=False)
            sudoers_file = Path(f"/etc/sudoers.d/90-{self.build_user}")
            sudoers_file.write_text(f"{self.build_user} ALL=(ALL) NOPASSWD: /usr/bin/pacman\n", encoding="utf-8")
            os.chmod(sudoers_file, 0o440)

    def enable_arch(self) -> None:
        """Bootstrap pacman config, Arch keyring, and sync official Arch repos."""
        print("[gem:arch] Enabling Arch Linux official repository bridge (core, extra, multilib)...")
        self.pacman_conf.parent.mkdir(parents=True, exist_ok=True)
        conf_text = ARCH_PACMAN_CONF_TEMPLATE.format(mirror=self.mirror)
        self.pacman_conf.write_text(conf_text, encoding="utf-8")

        # Also ensure /etc/pacman.conf exists so direct `pacman` and `makepkg -si` work seamlessly
        etc_pacman = Path("/etc/pacman.conf")
        if not etc_pacman.exists():
            etc_pacman.write_text(conf_text, encoding="utf-8")

        if not shutil.which("pacman"):
            print("[gem:arch] Note: `pacman` binary not yet present in PATH; config written to", self.pacman_conf)
            return

        if shutil.which("pacman-key"):
            if not Path("/etc/pacman.d/gnupg/pubring.gpg").exists():
                self._run(["pacman-key", "--init"], check=False)
            self._run(["pacman-key", "--populate", "archlinux"], check=False)

        self._run(["pacman", "--config", str(self.pacman_conf), "-Sy", "--noconfirm"], check=False)
        print("[gem:ecosystem] Upstream package mirror bridge is now active.")

    def enable_aur(self) -> None:
        """Enable AUR bridge and bootstrap `yay-bin` if not installed."""
        if not self.is_arch_enabled() or not self.pacman_conf.exists():
            self.enable_arch()

        print("[gem:aur] Enabling AUR bridge...")
        self.build_dir.mkdir(parents=True, exist_ok=True)
        if os.geteuid() == 0:
            self.ensure_build_user()
            self._run(["chown", "-R", f"{self.build_user}:{self.build_user}", str(self.build_dir)], check=False)

        if shutil.which("yay"):
            print("[gem:aur] `yay` is already installed and ready.")
            return

        if not shutil.which("git") or not shutil.which("makepkg"):
            print("[gem:aur] AUR bridge configured. Ensure `base-devel` and `git` are installed.")
            return

        yay_dir = self.build_dir / "yay-bin"
        if yay_dir.exists():
            shutil.rmtree(yay_dir)
        print("[gem:aur] Bootstrapping `yay-bin` from AUR...")
        self._run(["git", "clone", "https://aur.archlinux.org/yay-bin.git", str(yay_dir)], user=self.build_user, check=False)
        if yay_dir.exists():
            subprocess.run(
                ["sudo", "-u", self.build_user, "makepkg", "-si", "--noconfirm"],
                cwd=str(yay_dir),
                check=False,
            )
        print("[gem:aur] AUR bridge is now active.")

    def sync_arch(self) -> int:
        if not self.is_arch_enabled():
            return 0
        if not self.pacman_conf.exists():
            self.enable_arch()
        if not shutil.which("pacman"):
            return 0
        return subprocess.run(["pacman", "--config", str(self.pacman_conf), "-Sy", "--noconfirm"], check=False).returncode

    def upgrade_arch(self, noconfirm: bool = False) -> int:
        if not self.is_arch_enabled() or not shutil.which("pacman"):
            return 0
        cmd = ["pacman", "--config", str(self.pacman_conf), "-Syu"]
        if noconfirm:
            cmd.append("--noconfirm")
        return subprocess.run(cmd).returncode

    def search_arch(self, query: str) -> List[Dict]:
        if not self.is_arch_enabled() or not shutil.which("pacman"):
            return []
        proc = subprocess.run(
            ["pacman", "--config", str(self.pacman_conf), "-Ss", query],
            capture_output=True,
            text=True,
        )
        results = []
        lines = proc.stdout.splitlines()
        for i in range(0, len(lines), 2):
            header = lines[i].strip()
            desc = lines[i + 1].strip() if i + 1 < len(lines) else ""
            if "/" in header:
                repo_name, rest = header.split("/", 1)
                parts = rest.split()
                pkg_name = parts[0] if parts else rest
                version = parts[1] if len(parts) > 1 else ""
                results.append({
                    "name": pkg_name,
                    "version": version,
                    "description": desc,
                    "source": f"arch/{repo_name}",
                })
        return results

    def search_aur(self, query: str) -> List[Dict]:
        if not self.is_aur_enabled():
            return []
        url = f"{self.rpc_url}/search/{urllib.parse.quote(query)}"
        try:
            with urllib.request.urlopen(url, timeout=8) as resp:
                data = json.loads(resp.read().decode("utf-8"))
        except Exception:
            return []
        results = []
        for item in data.get("results", [])[:20]:
            results.append({
                "name": item.get("Name", ""),
                "version": item.get("Version", ""),
                "description": item.get("Description", ""),
                "source": "aur",
                "votes": item.get("NumVotes", 0),
            })
        return results

    def install_arch(self, packages: List[str], noconfirm: bool = False) -> int:
        if not self.is_arch_enabled():
            print("[gem:arch] Arch bridge is disabled. Run `sudo gem repo enable arch` first.", file=sys.stderr)
            return 1
        if not shutil.which("pacman"):
            print("[gem:arch] `pacman` is not installed on this host.", file=sys.stderr)
            return 1
        if not self.pacman_conf.exists():
            self.enable_arch()
        cmd = ["pacman", "--config", str(self.pacman_conf), "-S", "--needed"]
        if noconfirm:
            cmd.append("--noconfirm")
        cmd.extend(packages)
        return subprocess.run(cmd).returncode

    def install_aur(self, packages: List[str], noconfirm: bool = False) -> int:
        if not self.is_aur_enabled():
            print("[gem:aur] AUR bridge is disabled. Run `sudo gem repo enable aur` first.", file=sys.stderr)
            return 1

        if shutil.which("yay"):
            cmd = ["yay", "-S", "--needed"]
            if noconfirm:
                cmd.append("--noconfirm")
            cmd.extend(packages)
            if os.geteuid() == 0:
                self.ensure_build_user()
                cmd = ["sudo", "-u", self.build_user] + cmd
            return subprocess.run(cmd).returncode

        self.build_dir.mkdir(parents=True, exist_ok=True)
        for pkg in packages:
            pkg_dir = self.build_dir / pkg
            if pkg_dir.exists():
                shutil.rmtree(pkg_dir)
            print(f"[gem:aur] Cloning AUR package `{pkg}`...")
            clone_rc = subprocess.run(
                ["git", "clone", f"https://aur.archlinux.org/{pkg}.git", str(pkg_dir)]
            ).returncode
            if clone_rc != 0:
                print(f"[gem:aur] Failed to clone `{pkg}` from AUR.", file=sys.stderr)
                return clone_rc
            makepkg_cmd = ["makepkg", "-si"]
            if noconfirm:
                makepkg_cmd.append("--noconfirm")
            if os.geteuid() == 0:
                self.ensure_build_user()
                subprocess.run(["chown", "-R", f"{self.build_user}:{self.build_user}", str(pkg_dir)], check=False)
                makepkg_cmd = ["sudo", "-u", self.build_user] + makepkg_cmd
            rc = subprocess.run(makepkg_cmd, cwd=str(pkg_dir)).returncode
            if rc != 0:
                return rc
        return 0
